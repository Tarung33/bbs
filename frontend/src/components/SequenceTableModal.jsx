import React from 'react';
import { X, Table } from 'lucide-react';

export default function SequenceTableModal({ isOpen, onClose, bbsData, numberMode }) {
  if (!isOpen) return null;

  // Generate reference sequence for Explain Mode (p=7, q=11, n=77, s=3) or Real Crypto Mode
  const isExplain = numberMode === 'EXPLAIN';
  const p = isExplain ? 7 : (bbsData?.params?.p || 383);
  const q = isExplain ? 11 : (bbsData?.params?.q || 503);
  const n = p * q;
  const seed = isExplain ? 3 : (bbsData?.params?.seed || 10135);

  const rows = [];
  let currentX = (seed * seed) % n;

  for (let i = 0; i < 10; i++) {
    const prevX = currentX;
    currentX = (currentX * currentX) % n;
    const bit = currentX % 2;
    rows.push({
      step: i + 1,
      prevX,
      nextX: currentX,
      equation: `${prevX}² mod ${n}`,
      bit
    });
  }

  return (
    <div className="fixed inset-0 z-50 bg-[#111111]/60 flex items-center justify-center p-4 font-mono">
      <div className="bg-white border-2 border-[#111111] max-w-2xl w-full p-6 space-y-4 shadow-2xl animate-fadeIn">
        
        {/* Header */}
        <div className="flex justify-between items-center border-b border-[#111111] pb-3">
          <div className="flex items-center space-x-2 font-bold text-sm text-[#111111] uppercase tracking-wider">
            <Table className="w-4 h-4 text-[#111111]" />
            <span>REFERENCE SEQUENCE TABLE ({isExplain ? 'EXPLAIN MODE: p=7, q=11' : 'REAL CRYPTO MODE'})</span>
          </div>

          <button onClick={onClose} className="p-1 hover:bg-[#F7F7F5] text-[#111111] cursor-pointer">
            <X className="w-5 h-5" />
          </button>
        </div>

        <p className="text-xs text-[#555555] leading-relaxed">
          This reference table displays the mathematical sequence generated by repeated modular squaring. In the main visual machine experience, operations are shown one step at a time.
        </p>

        {/* Table */}
        <div className="border border-[#111111] max-h-80 overflow-y-auto">
          <table className="w-full text-left text-xs border-collapse">
            <thead>
              <tr className="bg-[#F7F7F5] border-b border-[#111111] text-[#111111] font-bold uppercase">
                <th className="p-2.5 border-r border-[#111111]">i</th>
                <th className="p-2.5 border-r border-[#111111]">xᵢ₋₁</th>
                <th className="p-2.5 border-r border-[#111111]">xᵢ = xᵢ₋₁² mod n</th>
                <th className="p-2.5">bᵢ = xᵢ mod 2</th>
              </tr>
            </thead>
            <tbody>
              {rows.map((row) => (
                <tr key={row.step} className="border-b border-[#E4E4E7] hover:bg-[#FAFAFA]">
                  <td className="p-2.5 border-r border-[#E4E4E7] font-bold text-[#111111]">{row.step}</td>
                  <td className="p-2.5 border-r border-[#E4E4E7] text-[#555555]">{row.prevX}</td>
                  <td className="p-2.5 border-r border-[#E4E4E7] font-bold text-[#111111]">{row.nextX} <span className="text-[#555555] font-normal text-[10px]">({row.equation})</span></td>
                  <td className="p-2.5 font-bold text-[#111111]">{row.bit}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>

        <div className="pt-2 text-right">
          <button
            onClick={onClose}
            className="px-4 py-2 bg-[#111111] text-white text-xs font-bold cursor-pointer hover:bg-[#333333]"
          >
            CLOSE REFERENCE TABLE
          </button>
        </div>

      </div>
    </div>
  );
}
